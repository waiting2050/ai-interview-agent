// listDueReviews returns cards whose due_at falls before the end of the
// caller's local day. tz_offset_minutes defaults to Asia/Shanghai (UTC+8).
func (h *handlers) listDueReviews(w http.ResponseWriter, r *http.Request) {
	if h.deps.Reviewer == nil {
		h.writeReviewUnavailable(w)
		return
	}
	offset := queryInt(r, "tz_offset_minutes", review.DefaultTZOffsetMinutes)
	limit := queryInt(r, "limit", 0)
	identity, _ := identityFrom(r.Context())
	result, err := h.deps.Reviewer.Due(r.Context(), identity.UserID, offset, limit)
	if err != nil {
		h.writeError(w, r, err)
		return
	}
	writeJSON(w, http.StatusOK, result)
}

// listReviews returns the cards generated by one interview session.
func (h *handlers) listReviews(w http.ResponseWriter, r *http.Request) {
	sessionID := r.URL.Query().Get("session_id")
	if sessionID == "" {
		h.writeError(w, r, fmt.Errorf("%w: session_id is required", review.ErrInvalidArgument))
		return
	}
	if _, ok := h.requireSessionOwnership(w, r, sessionID); !ok {
		return
	}
	if h.deps.Reviewer == nil {
		h.writeReviewUnavailable(w)
		return
	}
	identity, _ := identityFrom(r.Context())
	cards, err := h.deps.Reviewer.ListBySession(r.Context(), identity.UserID, sessionID)
	if err != nil {
		h.writeError(w, r, err)
		return
	}
	writeJSON(w, http.StatusOK, map[string]any{
		"session_id": sessionID,
		"count":      len(cards),
		"cards":      cards,
	})
}

func (h *handlers) getReview(w http.ResponseWriter, r *http.Request) {
	if h.deps.Reviewer == nil {
		h.writeReviewUnavailable(w)
		return
	}
	identity, _ := identityFrom(r.Context())
	card, err := h.deps.Reviewer.Get(r.Context(), identity.UserID, r.PathValue("id"))
	if err != nil {
		h.writeError(w, r, err)
		return
	}
	writeJSON(w, http.StatusOK, card)
}

type gradeReviewRequest struct {
	Grade *int `json:"grade"`
}

// gradeReview records self-assessed recall quality (0-5) and applies SM-2.
func (h *handlers) gradeReview(w http.ResponseWriter, r *http.Request) {
	if h.deps.Reviewer == nil {
		h.writeReviewUnavailable(w)
		return
	}
	var req gradeReviewRequest
	if err := decodeJSON(w, r, &req); err != nil {
		h.writeError(w, r, fmt.Errorf("%w: %s", review.ErrInvalidGrade, err))
		return
	}
	if req.Grade == nil {
		h.writeError(w, r, fmt.Errorf("%w: grade 必填", review.ErrInvalidGrade))
		return
	}
	identity, _ := identityFrom(r.Context())
	result, err := h.deps.Reviewer.Grade(r.Context(), identity.UserID, r.PathValue("id"), *req.Grade)
	if err != nil {
		h.writeError(w, r, err)
		return
	}
	writeJSON(w, http.StatusOK, result)
}

